"""Write firmware_info.h with this build's version and environment.

PlatformIO pre-script. The version is $FIRMWARE_VERSION (the release
workflow sets it from the tag) or else `git describe`. A local build without
a release tag gets a commit hash, which firmware_update.cpp treats as a
development build that never updates itself.

A generated header rather than a -D flag: a changing global define would
rebuild every library on each commit.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

Import("env")  # noqa: F821 (provided by PlatformIO)


def describe(project_dir: str) -> str:
    try:
        out = subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "dev"
    except (OSError, subprocess.CalledProcessError):
        return "dev"


version = os.environ.get("FIRMWARE_VERSION") or describe(env.subst("$PROJECT_DIR"))  # noqa: F821
if version[:1] in ("v", "V"):
    version = version[1:]
variant = env.subst("$PIOENV")  # noqa: F821

out_dir = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821
out_dir.mkdir(parents=True, exist_ok=True)
header = out_dir / "firmware_info.h"
text = (
    "#pragma once\n"
    "// Generated by scripts/firmware_version.py.\n"
    f'#define FIRMWARE_VERSION "{version}"\n'
    f'#define FIRMWARE_VARIANT "{variant}"\n'
)
if not header.exists() or header.read_text() != text:
    header.write_text(text)
env.Append(CPPPATH=[str(out_dir)])  # noqa: F821
print(f"firmware version {version} ({variant})")
