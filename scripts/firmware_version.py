"""Stamp the firmware with its version (PlatformIO pre-script).

The release number lives in VERSION at the repo root. A build from the
commit tagged v<VERSION> with no local changes is just that number; any
other build adds the commit, and "dirty" for uncommitted changes, e.g.
1.0.0+f920599.dirty, so a board always says what it is running.

Writes firmware/src/firmware_version.cpp (gitignored), and only when the
string changed, so an unchanged tree doesn't recompile it.
Run directly to print the version.
"""

from __future__ import annotations

import subprocess
from pathlib import Path


def project_dir() -> Path:
    pio_env = globals().get("env")
    if pio_env is not None:
        return Path(str(pio_env["PROJECT_DIR"]))
    return Path(__file__).resolve().parents[1]


def git(root: Path, *args: str) -> str | None:
    try:
        out = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip()


def firmware_version(root: Path) -> str:
    release = (root / "VERSION").read_text(encoding="utf-8").strip()
    commit = git(root, "rev-parse", "--short", "HEAD")
    if commit is None:
        return release + "+nogit"
    dirty = bool(git(root, "status", "--porcelain", "--untracked-files=no"))
    tagged = git(root, "tag", "--points-at", "HEAD")
    if not dirty and tagged is not None and f"v{release}" in tagged.split():
        return release
    return f"{release}+{commit}" + (".dirty" if dirty else "")


def write_source(root: Path, version: str) -> None:
    path = root / "firmware" / "src" / "firmware_version.cpp"
    text = (
        "// Generated by scripts/firmware_version.py - do not edit.\n"
        '#include "firmware_version.h"\n\n'
        f'const char kFirmwareVersion[] = "{version}";\n'
    )
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")


if "Import" in globals():  # running under PlatformIO/SCons
    Import("env")  # noqa: F821
    root = project_dir()
    version = firmware_version(root)
    write_source(root, version)
    print(f"firmware version {version}")
elif __name__ == "__main__":
    print(firmware_version(project_dir()))
