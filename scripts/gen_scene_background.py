"""Bakes a background image into firmware/src/scene_background.{h,cpp}.

The image is cropped to the 5:3 panel aspect so its horizon lands at
--horizon (fraction of output height), scaled to 400x240 and Floyd-Steinberg
dithered to RGB565. rower_scene draws the boat on top and uses the exported
horizon / sun position to line its camera and sun glints up with the photo.

Current asset: assets/scene_background.jpg, generated with Higgsfield
(Nano Banana Pro), dusk lake, no boat.

    python3 scripts/gen_scene_background.py assets/scene_background.jpg \
        --src-horizon 0.4727 --src-sun-x 0.2936 --horizon 0.333
"""
import argparse
from pathlib import Path

import numpy as np
from PIL import Image

OUT_W, OUT_H = 400, 240
ROOT = Path(__file__).resolve().parent.parent

ap = argparse.ArgumentParser()
ap.add_argument("src")
ap.add_argument("--src-horizon", type=float, required=True, help="waterline y in the source, fraction of height")
ap.add_argument("--src-sun-x", type=float, required=True, help="sun x in the source, fraction of width")
ap.add_argument("--horizon", type=float, required=True, help="waterline y in the output, fraction of height")
ap.add_argument("--center-x", type=float, default=0.5, help="crop centre x in the source, fraction of width")
args = ap.parse_args()

im = Image.open(args.src).convert("RGB")
sw, sh = im.size
hy = args.src_horizon * sh

# Largest 5:3 crop that puts the horizon at the requested output fraction.
crop_h = min(hy / args.horizon if args.horizon > 0 else sh, (sh - hy) / (1.0 - args.horizon), sw * OUT_H / OUT_W)
crop_w = crop_h * OUT_W / OUT_H
top = hy - args.horizon * crop_h
left = min(max(args.center_x * sw - crop_w / 2, 0), sw - crop_w)
im = im.resize((OUT_W, OUT_H), Image.LANCZOS, box=(left, top, left + crop_w, top + crop_h))
sun_x = (args.src_sun_x * sw - left) / crop_w

# Floyd-Steinberg to RGB565: hides banding in the sky gradient.
px = np.asarray(im, dtype=np.float32).copy()
levels = np.array([31.0, 63.0, 31.0])
out = np.zeros((OUT_H, OUT_W), dtype=np.uint16)
for y in range(OUT_H):
    for x in range(OUT_W):
        old = np.clip(px[y, x], 0, 255)
        q = np.round(old / 255.0 * levels)
        err = old - q / levels * 255.0
        out[y, x] = (int(q[0]) << 11) | (int(q[1]) << 5) | int(q[2])
        if x + 1 < OUT_W:
            px[y, x + 1] += err * 7 / 16
        if y + 1 < OUT_H:
            if x > 0:
                px[y + 1, x - 1] += err * 3 / 16
            px[y + 1, x] += err * 5 / 16
            if x + 1 < OUT_W:
                px[y + 1, x + 1] += err * 1 / 16

src_dir = ROOT / "firmware" / "src"
(src_dir / "scene_background.h").write_text(f"""#pragma once

#include <cstdint>

// Generated by scripts/gen_scene_background.py - do not edit.
// Static sky + water photo under the procedural rower (see rower_scene.cpp).
namespace scene_background {{

constexpr int kWidth = {OUT_W};
constexpr int kHeight = {OUT_H};
// Waterline row and sun column, in kWidth x kHeight pixels.
constexpr float kHorizonY = {args.horizon * OUT_H:.2f}f;
constexpr float kSunX = {sun_x * OUT_W:.2f}f;

// RGB565 (LVGL native byte order), row-major.
extern const uint16_t kPixels[kWidth * kHeight];

}} // namespace scene_background
""")

lines = [
    "// Generated by scripts/gen_scene_background.py - do not edit.",
    '#include "scene_background.h"',
    "",
    "namespace scene_background {",
    "",
    "const uint16_t kPixels[kWidth * kHeight] = {",
]
flat = out.flatten()
for i in range(0, len(flat), 16):
    lines.append("    " + ", ".join(f"0x{v:04x}" for v in flat[i:i + 16]) + ",")
lines += ["};", "", "} // namespace scene_background", ""]
(src_dir / "scene_background.cpp").write_text("\n".join(lines))

print(f"crop {crop_w:.0f}x{crop_h:.0f} at ({left:.0f},{top:.0f}); horizon {args.horizon * OUT_H:.1f}px, sun x {sun_x * OUT_W:.1f}px")
